def kr_checkpoint(model: str, fold: int, epoch: int) -> str:
    """Where the evaluation configs expect the KR-rPPG fold models that users train with kr_kfold/train."""
    return f"${{KR_RPPG_CHECKPOINTS}}/kr_5fold/{model}/KFold_{model}_fold{fold}_Epoch{epoch}.pth"


def cache_dir(dataset: str, cache: str) -> str:
    return f"${{KR_RPPG_WORK}}/cache/{dataset}/{cache}"


def data_section(dataset: str, cache: str, begin: float = 0.0, end: float = 1.0,
                 do_preprocess: bool = False, data_format: str = "") -> dict:
    ds, cc = DATASETS[dataset], CACHES[cache]
    section = {
        "FS": ds["FS"],
        "DATASET": ds["DATASET"],
        "DO_PREPROCESS": do_preprocess,
        "DATA_FORMAT": data_format or cc["DATA_FORMAT"],
        "DATA_PATH": ds["DATA_PATH"],
        "CACHED_PATH": cache_dir(dataset, cache),
        "EXP_DATA_NAME": "",
        "BEGIN": begin,
        "END": end,
        "PREPROCESS": {
            "DATA_TYPE": list(cc["DATA_TYPE"]),
            "DATA_AUG": ["None"],
            "LABEL_TYPE": "DiffNormalized",
            "DO_CHUNK": True,
            "CHUNK_LENGTH": cc["CHUNK_LENGTH"],
            "CROP_FACE": {
                "DO_CROP_FACE": True,
                "BACKEND": "HC",
                "USE_LARGE_FACE_BOX": True,
                "LARGE_BOX_COEF": 1.5,
                "DETECTION": {"DO_DYNAMIC_DETECTION": False, "DYNAMIC_DETECTION_FREQUENCY": ds["DET_LEN"],
                              "USE_MEDIAN_FACE_BOX": False},
            },
            "RESIZE": {"H": cc["SIZE"], "W": cc["SIZE"]},
        },
    }
    if dataset == "mmpd":
        section["INFO"] = copy.deepcopy(MMPD_INFO)
    if dataset == "ubfc_phys":
        section["FILTERING"] = {"USE_EXCLUSION_LIST": True, "EXCLUSION_LIST": list(UBFC_PHYS_EXCLUSION_LIST),
                                "SELECT_TASKS": True, "TASK_LIST": ["T1", "T2", "T3"]}
    return section


def kfold(section: dict, fold: int, test_fold: bool, fold_name: str) -> dict:
    section = dict(section)
    section["KFOLD_CSV"] = "${KR_RPPG_ROOT}/metadata/fold_assignment.csv"
    section["KFOLD_ID"] = fold
    if test_fold:
        section["KFOLD_TEST_FOLD"] = True
    section["FOLD"] = {"FOLD_NAME": fold_name, "FOLD_PATH": ""}
    return section


def inference(model_path: str, batch_size: int = 4) -> dict:
    return {"BATCH_SIZE": batch_size, "EVALUATION_METHOD": "FFT",
            "EVALUATION_WINDOW": {"USE_SMALLER_WINDOW": False, "WINDOW_SIZE": 10}, "MODEL_PATH": model_path}


def base(mode: str, model: str, log_path: str) -> dict:
    return {"BASE": [""], "TOOLBOX_MODE": mode, "DEVICE": "cuda:0", "NUM_OF_GPU_TRAIN": 1,
            "LOG": {"PATH": log_path}, "MODEL": copy.deepcopy(ARCH[model]["MODEL"])}


def test_only(model: str, test: dict, model_path: str, log_path: str, batch_size: int = 4) -> dict:
    cfg = base("only_test", model, log_path)
    cfg["TEST"] = {"METRICS": list(METRICS), "USE_LAST_EPOCH": True, "DATA": test}
    cfg["INFERENCE"] = inference(model_path, batch_size)
    return cfg


def train_block(model: str, name: str) -> dict:
    t = ARCH[model]["TRAIN"]
    return {"BATCH_SIZE": t["BATCH_SIZE"], "EPOCHS": t["EPOCHS"], "LR": t["LR"], "MODEL_FILE_NAME": name,
            "PLOT_LOSSES_AND_LR": False}


# --- experiment families -------------------------------------------------------------------------

def preprocess_configs() -> Dict[str, dict]:
    """One cache per dataset x input pipeline; built by benchmark/preprocess.py (no model involved)."""
    out = {}
    for dataset in DATASETS:
        for cache in CACHES:
            test = data_section(dataset, cache, do_preprocess=True)
            out[f"preprocess/{dataset}_{cache}.yaml"] = test_only(
                cache, test, "", f"${{KR_RPPG_WORK}}/runs/preprocess/{dataset}_{cache}")
    return out


def kr_kfold_configs() -> Dict[str, dict]:
    out = {}
    for fold in FOLDS:
        for model in MODELS:
            cache = ARCH[model]["CACHE"]
            cfg = base("train_and_test", model, f"${{KR_RPPG_WORK}}/runs/kr_kfold/{model}_fold{fold}")
            cfg["TRAIN"] = train_block(model, f"KFold_{model}_fold{fold}")
            cfg["TRAIN"]["DATA"] = kfold(data_section("kr", cache, 0.0, 0.9), fold, False, f"kfold{fold}")
            cfg["VALID"] = {"DATA": kfold(data_section("kr", cache, 0.9, 1.0), fold, False, f"kfold{fold}")}
            # Post-training test inside the train pool, as in the manuscript runs; the reported numbers
            # come from the separate out-of-fold evaluation configs (kr_kfold/eval).
            cfg["TEST"] = {"METRICS": list(METRICS), "USE_LAST_EPOCH": False,
                           "DATA": kfold(data_section("kr", cache, 0.85, 1.0), fold, False, f"kfold{fold}")}
            cfg["INFERENCE"] = inference("")
            out[f"kr_kfold/train/fold{fold}_{model}.yaml"] = cfg

            epoch = KR_EPOCHS_INTERNAL[model][fold]
            test = kfold(data_section("kr", cache), fold, True, f"kfold{fold}_testfold")
            out[f"kr_kfold/eval/fold{fold}_{model}.yaml"] = test_only(
                model, test, kr_checkpoint(model, fold, epoch),
                f"${{KR_RPPG_WORK}}/runs/kr_kfold_eval/{model}_fold{fold}")
    return out


def kr_to_external_configs() -> Dict[str, dict]:
    out = {}
    for dataset in ("pure", "ubfc_rppg", "mmpd", "ubfc_phys"):
        for model in MODELS:
            for fold in FOLDS:
                cache = ARCH[model]["CACHE"]
                test = data_section(dataset, cache)
                if dataset == "ubfc_phys":
                    test["FILE_LIST_PATH"] = cache_dir(dataset, cache) + "/DataFileLists"
                batch = 32 if dataset == "mmpd" and model != "deepphys" else 4
                # PhysFormer fold models keep the default gra_sharp (THETA = 0.7), the value they were trained with.
                cfg = test_only(model, test, kr_checkpoint(model, fold, KR_EPOCHS_EXTERNAL[model][fold]),
                                f"${{KR_RPPG_WORK}}/runs/kr_to_{dataset}/{model}_fold{fold}", batch)
                out[f"kr_to_{dataset}/{model}_fold{fold}.yaml"] = cfg
    return out


def external_to_kr_configs() -> Dict[str, dict]:
    out = {}
    for source in ("pure", "ubfc_rppg"):
        for model in MODELS:
            cache = EXTERNAL_TO_KR_CACHE.get(model, ARCH[model]["CACHE"])
            test = data_section("kr", cache, data_format=ARCH[model]["DATA_FORMAT"])
            path = f"${{RPPG_TOOLBOX_WEIGHTS}}/{UPSTREAM_WEIGHTS[source][model]}"
            cfg = test_only(model, test, path, f"${{KR_RPPG_WORK}}/runs/{source}_to_kr/{model}")
            if model == "physformer":  # official weights: score with the gra_sharp they were trained with
                cfg["MODEL"]["PHYSFORMER"]["GRA_SHARP"] = UPSTREAM_PHYSFORMER_GRA_SHARP
            out[f"{source}_to_kr/{model}.yaml"] = cfg
    return out


def mmpd_to_kr_configs() -> Dict[str, dict]:
    """MMPD subjects 1-26 train, 27-33 validation (lists from benchmark/make_mmpd_split.py), test = all KR."""
    out = {}
    for model in MODELS:
        cache = ARCH[model]["CACHE"]
        split = "${KR_RPPG_WORK}/splits/mmpd_" + cache
        name = f"Table8_MMPD_to_KR_{model}_s01_26"

        def mmpd(begin: float, end: float, which: str) -> dict:
            section = data_section("mmpd", cache, begin, end)
            section["FILE_LIST_PATH"] = f"{split}_{which}.csv"
            return section

        cfg = base("train_and_test", model, f"${{KR_RPPG_WORK}}/runs/mmpd_to_kr/{model}")
        cfg["TRAIN"] = train_block(model, name)
        cfg["TRAIN"]["DATA"] = mmpd(0.0, 0.8, "train_subjects_01_26")
        cfg["VALID"] = {"DATA": mmpd(0.8, 1.0, "valid_subjects_27_33")}
        cfg["TEST"] = {"METRICS": list(METRICS), "USE_LAST_EPOCH": False, "DATA": data_section("kr", cache)}
        cfg["INFERENCE"] = inference("")
        out[f"mmpd_to_kr/train/{model}.yaml"] = cfg

        path = f"${{KR_RPPG_CHECKPOINTS}}/mmpd_trained/{model}/{name}_Epoch{MMPD_EPOCHS[model]}.pth"
        out[f"mmpd_to_kr/eval/{model}.yaml"] = test_only(
            model, data_section("kr", cache), path, f"${{KR_RPPG_WORK}}/runs/mmpd_to_kr_eval/{model}")
    return out


def all_configs() -> Dict[str, dict]:
    out: Dict[str, dict] = {}
    for family in (preprocess_configs, kr_kfold_configs, kr_to_external_configs, external_to_kr_configs,
                   mmpd_to_kr_configs):
        out.update(family())
    return out


class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):  # yaml API: never emit &id anchors
        return True


def render(cfg: dict) -> str:
    return HEADER + yaml.dump(cfg, Dumper=_NoAliasDumper, default_flow_style=False, sort_keys=False)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=OUT_DIR)
    parser.add_argument("--check", action="store_true", help="only compare with the files on disk")
    args = parser.parse_args(argv)

    configs = all_configs()
    stale: List[Tuple[str, str]] = []
    for rel, cfg in sorted(configs.items()):
        path = args.out / rel
        text = render(cfg)
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append((rel, "missing" if not path.exists() else "differs"))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    extra = sorted(str(p.relative_to(args.out)) for p in args.out.rglob("*.yaml")
                   if str(p.relative_to(args.out)) not in configs) if args.out.exists() else []
    if args.check:
        for rel, why in stale:
            print(f"stale: {rel} ({why})")
        for rel in extra:
            print(f"unexpected: {rel}")
        return 1 if stale or extra else 0
    print(f"wrote {len(configs)} configs to {args.out}" + (f"; unexpected extra files: {extra}" if extra else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
